tic_t rendergametic;

void D_SRB2Loop(void)
{
	tic_t entertic = 0, oldentertics = 0, realtics = 0, rendertimeout = INFTICS;
	double deltatics = 0.0;

	boolean interp = false;
	boolean doDisplay = false;
	int frameskip = 0;

	if (dedicated)
		server = true;

	// Pushing of + parameters is now done back in D_SRB2Main, not here.

	I_UpdateTime(cv_timescale.value);
	oldentertics = I_GetTime();

	// end of loading screen: CONS_Printf() will no more call FinishUpdate()
	con_startup = false;

	// make sure to do a d_display to init mode _before_ load a level
	SCR_SetMode(); // change video mode
	SCR_Recalc();

	chosenrendermode = render_none;

	// Check and print which version is executed.
	// Use this as the border between setup and the main game loop being entered.
	CONS_Printf(
	"===========================================================================\n"
	"                   We hope you enjoy this game as\n"
	"                     much as we did making it!\n"
	"===========================================================================\n");

	// hack to start on a nice clear console screen.
	COM_ImmedExecute("cls;version");

	I_FinishUpdate(); // page flip or blit buffer
	/*
	LMFAO this was showing garbage under OpenGL
	because I_FinishUpdate was called afterward
	*/

#if 0
	/* Smells like a hack... Don't fade Sonic's ass into the title screen. */
	if (gamestate != GS_TITLESCREEN)
	{
		static lumpnum_t gstartuplumpnum = W_CheckNumForName("STARTUP");
		if (gstartuplumpnum == LUMPERROR)
			gstartuplumpnum = W_GetNumForName("MISSING");
		V_DrawScaledPatch(0, 0, 0, W_CachePatchNum(gstartuplumpnum, PU_PATCH));
	}
#endif

	for (;;)
	{
		precise_t enterprecise = I_GetPreciseTime();

		g_dc = {};
		Z_Frame_Reset();

		I_UpdateTime(cv_timescale.value);

		if (lastwipetic)
		{
			oldentertics = lastwipetic;
			lastwipetic = 0;
		}

		// get real tics
		entertic = I_GetTime();
		realtics = entertic - oldentertics;
		oldentertics = entertic;

		refreshdirmenu = 0; // not sure where to put this, here as good as any?

		if (demo.playback && gamestate == GS_LEVEL)
		{
			// Nicer place to put this.
			realtics = realtics * cv_playbackspeed.value;
		}

#ifdef DEBUGFILE
		if (!realtics)
			if (debugload)
				debugload--;
#endif

		interp = !dedicated && (R_GetFramerateCap() != TICRATE || cv_timescale.value < FRACUNIT);
		doDisplay = false;

#ifdef HW3SOUND
		HW3S_BeginFrameUpdate();
#endif
		I_UpdateTime(cv_timescale.value);

		if (realtics > 0 || singletics)
		{
			// don't skip more than 10 frames at a time
			// (fadein / fadeout cause massive frame skip!)
			if (realtics > 8)
				realtics = 1;

			I_UpdateTime(cv_timescale.value);

			// process tics (but maybe not if realtic == 0)
			{
				ZoneScopedN("TryRunTics");
				TryRunTics(realtics);
			}

			if (lastdraw || singletics || gametic > rendergametic)
			{
				rendergametic = gametic;
				rendertimeout = entertic + TICRATE/17;

				doDisplay = true;
			}
			else if (rendertimeout < entertic) // in case the server hang or netsplit
			{
				// Lagless camera! Yay!
				if (cv_laglesscam.value && gamestate == GS_LEVEL && netgame)
				{
					// Evaluate the chase cam once for every local realtic
					// This might actually be better suited inside G_Ticker or TryRunTics
					for (tic_t chasecamtics = 0; chasecamtics < realtics; chasecamtics++)
					{
						P_RunChaseCameras();
					}
					R_UpdateViewInterpolation();
				}

				doDisplay = true;
			}

			renderisnewtic = true;
		}
		else
		{
			renderisnewtic = false;
		}

		I_UpdateTime(cv_timescale.value);

		if (interp)
		{
			renderdeltatics = FLOAT_TO_FIXED(deltatics);

			const boolean lagging = ((deltatics >= 1.0) || hu_stopped);

			I_UpdateTime(cv_timescale.value);

			R_SetTimeFrac(lagging ? FRACUNIT : g_time.timefrac);
		}
		else
		{
			renderdeltatics = realtics * FRACUNIT;
			R_SetTimeFrac(FRACUNIT);
		}

		I_UpdateTime(cv_timescale.value);

		if (interp || doDisplay)
		{
			if (!frameskip)
			{
				D_Display();
			}
			else if (!dedicated && frameskip)
			{
				// always update console and hud
				// otherwise it may take minutes to open it
				CON_Drawer();

				if (gamestate == GS_LEVEL)
				{
					ST_Drawer();
					HU_Drawer();
				}
			}
		}

		// Only take screenshots after drawing.
		if (moviemode)
			M_SaveFrame();
		if (takescreenshot)
			M_DoScreenShot();

		// consoleplayer -> displayplayers (hear sounds from viewpoint)
		S_UpdateSounds(); // move positional sounds
		if (renderisnewtic)
			S_UpdateClosedCaptions();

#ifdef HW3SOUND
		HW3S_EndFrameUpdate();
#endif

		LUA_Step();

#ifdef HAVE_DISCORDRPC
		if (! dedicated)
		{
			Discord_RunCallbacks();
		}
#endif

		deltatics = D_EndFrame(enterprecise, &frameskip);

		// Wipes run an inner loop and artificially increase
		// the measured time.
		if (ranwipe)
		{
			double deltamath = (R_GetFramerateCap() == 0) ? 35.0 : 35.0 / R_GetFramerateCap();
			deltatics = deltamath;
			frameskip = 0;
			ranwipe = false;
		}
	}
}

